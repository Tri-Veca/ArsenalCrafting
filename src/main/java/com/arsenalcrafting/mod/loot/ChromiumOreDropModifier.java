package com.arsenalcrafting.mod.loot;

import com.arsenalcrafting.mod.registry.ModItems;
import com.mojang.serialization.MapCodec;
import com.mojang.serialization.codecs.RecordCodecBuilder;
import it.unimi.dsi.fastutil.objects.ObjectArrayList;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.level.storage.loot.LootContext;
import net.minecraft.world.level.storage.loot.predicates.LootItemCondition;
import net.neoforged.neoforge.common.loot.IGlobalLootModifier;
import net.neoforged.neoforge.common.loot.LootModifier;

/**
 * Adds a chance for chromium to drop from qualifying ore blocks on top of their normal
 * loot. One instance per rarity tier (common/mid/rare), each with its own chromiumChance,
 * generated by ChromiumLootModifierProvider — one per vanilla ore.
 */
public class ChromiumOreDropModifier extends LootModifier {

    public static final MapCodec<ChromiumOreDropModifier> CODEC = RecordCodecBuilder.mapCodec(inst ->
            codecStart(inst)
                    .and(com.mojang.serialization.Codec.FLOAT.fieldOf("chromium_chance").forGetter(m -> m.chromiumChance))
                    .apply(inst, ChromiumOreDropModifier::new));

    private final float chromiumChance;

    public ChromiumOreDropModifier(LootItemCondition[] conditions, float chromiumChance) {
        super(conditions);
        this.chromiumChance = chromiumChance;
    }

    @Override
    protected ObjectArrayList<ItemStack> doApply(ObjectArrayList<ItemStack> generatedLoot, LootContext context) {
        if (context.getRandom().nextFloat() < chromiumChance) {
            generatedLoot.add(new ItemStack(ModItems.CHROMIUM.get()));
        }
        return generatedLoot;
    }

    @Override
    public MapCodec<? extends IGlobalLootModifier> codec() {
        return CODEC;
    }
}