package com.arsenalcrafting.mod.generator;

import com.arsenalcrafting.mod.ArsenalCrafting;
import com.arsenalcrafting.mod.blocks.AlloySmelterBlock;
import com.arsenalcrafting.mod.blocks.CasingBlock;
import com.arsenalcrafting.mod.blocks.LavaTankBlock;
import com.arsenalcrafting.mod.registry.ModBlocks;
import net.minecraft.core.Direction;
import net.minecraft.data.PackOutput;
import net.minecraft.world.level.block.Block;
import net.neoforged.neoforge.client.model.generators.BlockStateProvider;
import net.neoforged.neoforge.client.model.generators.ConfiguredModel;
import net.neoforged.neoforge.common.data.ExistingFileHelper;

/**
 * Links Registry Blocks to their corresponding JSON models.
 */
public class ArsenalBlockStateProvider extends BlockStateProvider {

    public ArsenalBlockStateProvider(PackOutput output, ExistingFileHelper exFileHelper) {
        super(output, ArsenalCrafting.MOD_ID, exFileHelper);
    }

    @Override
    protected void registerStatesAndModels() {
        System.out.println("[BlockStateProvider] Linking molds to models...");

        // Loop through our automated mold map
        ModBlocks.MOLD_BLOCKS.values().forEach(holder -> {
            String name = holder.getId().getPath();

            // simpleBlock() is the method that creates the blockstate JSON.
            // We point it to the model file generated by ArsenalBlockModelProvider.
            simpleBlock(holder.get(), models().getExistingFile(modLoc("block/" + name)));
        });

        // Link Bronze Molds
        ModBlocks.BRONZE_MOLD_BLOCKS.values().forEach(holder -> {
            simpleBlock(holder.get(), models().getExistingFile(modLoc("block/" + holder.getId().getPath())));
        });

        // Add any other static blocks here if needed
        // simpleBlock(ModBlocks.LAVA_TANK.get());


        // Alloy Smelter blockstates
        String[] smeltTiers = {"unformed", "copper", "iron", "bronze", "steel", "titanium"};

        getVariantBuilder(ModBlocks.ALLOY_SMELTER.get()).forAllStates(state -> {
            String tier = state.getValue(AlloySmelterBlock.TIER).getSerializedName();
            boolean active = state.getValue(AlloySmelterBlock.ACTIVE);
            Direction facing = state.getValue(AlloySmelterBlock.FACING);

            String modelName = "alloy_smelter_" + tier + "_" + (active ? "on" : "off");

            int yRot = switch (facing) {
                case SOUTH -> 180;
                case WEST -> 270;
                case EAST -> 90;
                default -> 0; // NORTH
            };

            return ConfiguredModel.builder()
                    .modelFile(models().getExistingFile(modLoc("block/" + modelName)))
                    .rotationY(yRot)
                    .uvLock(true)
                    .build();
        });

        // Lava Tank blockstates
        getVariantBuilder(ModBlocks.LAVA_TANK.get()).forAllStates(state -> {
            String tier = state.getValue(LavaTankBlock.TIER).getSerializedName();
            Direction facing = state.getValue(LavaTankBlock.FACING);

            String modelName = "lava_tank_" + tier;

            int yRot = switch (facing) {
                case SOUTH -> 180;
                case WEST -> 270;
                case EAST -> 90;
                default -> 0;
            };

            return ConfiguredModel.builder()
                    .modelFile(models().getExistingFile(modLoc("block/" + modelName)))
                    .rotationY(yRot)
                    .uvLock(true)
                    .build();
        });


        // Casing Blockstates with facing and drain variants
        Direction[] facings = {Direction.NORTH, Direction.SOUTH, Direction.EAST, Direction.WEST};

// Copper Casing
        for (Direction facing : facings) {
            getVariantBuilder(ModBlocks.COPPER_CASING.get())
                    .partialState()
                    .with(CasingBlock.FACING, facing)
                    .with(CasingBlock.DRAIN, false)
                    .modelForState()
                    .modelFile(models().getExistingFile(modLoc("block/copper_casing")))
                    .addModel()
                    .partialState()
                    .with(CasingBlock.FACING, facing)
                    .with(CasingBlock.DRAIN, true)
                    .modelForState()
                    .modelFile(models().getExistingFile(modLoc("block/copper_casing_drain")))
                    .rotationY(getYRotation(facing))
                    .uvLock(true)
                    .addModel();
        }

// Iron Casing
        for (Direction facing : facings) {
            getVariantBuilder(ModBlocks.IRON_CASING.get())
                    .partialState()
                    .with(CasingBlock.FACING, facing)
                    .with(CasingBlock.DRAIN, false)
                    .modelForState()
                    .modelFile(models().getExistingFile(modLoc("block/iron_casing")))
                    .addModel()
                    .partialState()
                    .with(CasingBlock.FACING, facing)
                    .with(CasingBlock.DRAIN, true)
                    .modelForState()
                    .modelFile(models().getExistingFile(modLoc("block/iron_casing_drain")))
                    .rotationY(getYRotation(facing))
                    .uvLock(true)
                    .addModel();
        }

// Bronze Casing
        for (Direction facing : facings) {
            getVariantBuilder(ModBlocks.BRONZE_CASING.get())
                    .partialState()
                    .with(CasingBlock.FACING, facing)
                    .with(CasingBlock.DRAIN, false)
                    .modelForState()
                    .modelFile(models().getExistingFile(modLoc("block/bronze_casing")))
                    .addModel()
                    .partialState()
                    .with(CasingBlock.FACING, facing)
                    .with(CasingBlock.DRAIN, true)
                    .modelForState()
                    .modelFile(models().getExistingFile(modLoc("block/bronze_casing_drain")))
                    .rotationY(getYRotation(facing))
                    .uvLock(true)
                    .addModel();
        }

// Steel Casing
        for (Direction facing : facings) {
            getVariantBuilder(ModBlocks.STEEL_CASING.get())
                    .partialState()
                    .with(CasingBlock.FACING, facing)
                    .with(CasingBlock.DRAIN, false)
                    .modelForState()
                    .modelFile(models().getExistingFile(modLoc("block/steel_casing")))
                    .addModel()
                    .partialState()
                    .with(CasingBlock.FACING, facing)
                    .with(CasingBlock.DRAIN, true)
                    .modelForState()
                    .modelFile(models().getExistingFile(modLoc("block/steel_casing_drain")))
                    .rotationY(getYRotation(facing))
                    .uvLock(true)
                    .addModel();
        }

// Titanium Casing
        for (Direction facing : facings) {
            getVariantBuilder(ModBlocks.TITANIUM_CASING.get())
                    .partialState()
                    .with(CasingBlock.FACING, facing)
                    .with(CasingBlock.DRAIN, false)
                    .modelForState()
                    .modelFile(models().getExistingFile(modLoc("block/titanium_casing")))
                    .addModel()
                    .partialState()
                    .with(CasingBlock.FACING, facing)
                    .with(CasingBlock.DRAIN, true)
                    .modelForState()
                    .modelFile(models().getExistingFile(modLoc("block/titanium_casing_drain")))
                    .rotationY(getYRotation(facing))
                    .uvLock(true)
                    .addModel();
        }

    }

    private int getYRotation(Direction facing) {
        return switch (facing) {
            case SOUTH -> 180;
            case WEST -> 270;
            case EAST -> 90;
            default -> 0;
        };

    }
}